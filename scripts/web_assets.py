# Pre-build script: each web/*.html, stylesheets and scripts inlined, minified by line and gzipped, into $BUILD_DIR/generated/WebAssets.h only.
import gzip
import hashlib
import re
import sys
from pathlib import Path

Import("env")  # noqa: F821 (provided by PlatformIO)

STYLESHEET = re.compile(r'<link rel="stylesheet" href="([^"/]+\.css)">')
SCRIPT = re.compile(r'<script src="([^"/]+\.js)"></script>')
HTML_COMMENT = re.compile(r"<!--.*?-->", re.S)
CSS_COMMENT = re.compile(r"/\*.*?\*/", re.S)
BYTES_PER_LINE = 16


def fail(message):
    sys.stderr.write("web_assets: " + message + "\n")
    env.Exit(1)  # noqa: F821


# Nothing inside a line changes, so pages hold no multi-line template literals and no static <pre> text.
def squeeze(text):
    lines = (line.strip() for line in text.splitlines())

    return "\n".join(line for line in lines if line and not line.startswith("//")) + "\n"


# The text of the file of web/ that a page links.
def linked(page, web_dir, name):
    path = web_dir / name

    if not path.is_file():
        fail(page.name + " links " + name + ", which is not in web/")

    return path.read_text(encoding="utf-8")


def inline_files(page, web_dir):
    def style(match):
        return "<style>\n" + squeeze(CSS_COMMENT.sub("", linked(page, web_dir, match.group(1)))) + "</style>"

    def script(match):
        return "<script>\n" + squeeze(linked(page, web_dir, match.group(1))) + "</script>"

    return SCRIPT.sub(script, STYLESHEET.sub(style, page.read_text(encoding="utf-8")))


# index.html -> indexHtml
def array_name(file_name):
    return re.sub(r"[^0-9A-Za-z]+([0-9A-Za-z])", lambda m: m.group(1).upper(), file_name)


def array_lines(data):
    for start in range(0, len(data), BYTES_PER_LINE):
        yield "  " + ", ".join("0x%02x" % b for b in data[start:start + BYTES_PER_LINE]) + ","


def generate(web_dir):
    pages = sorted(web_dir.glob("*.html"))

    if not pages:
        fail("no .html files in " + str(web_dir))

    out = [
        "// Generated by scripts/web_assets.py from web/ before every build; do not edit, not in git.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace w2b",
        "{",
        "",
        "namespace webassets",
        "{",
    ]

    for page in pages:
        source = page.read_bytes()
        minified = squeeze(HTML_COMMENT.sub("", inline_files(page, web_dir))).encode("utf-8")
        # mtime=0: the same input gives the same bytes
        packed = gzip.compress(minified, compresslevel=9, mtime=0)
        print("web_assets: %s %d B; stylesheets and scripts inlined, minified %d B; gzip %d B" % (page.name, len(source), len(minified), len(packed)))

        out += ["", "// web/%s: %d B; stylesheets and scripts inlined, minified %d B; gzip %d B" % (page.name, len(source), len(minified), len(packed))]
        out += ["const uint8_t %s[] = {" % array_name(page.name)]
        out += list(array_lines(packed))
        out += ["};"]
        # the entity tag, from the bytes: a browser's reload of the page it holds gets 304 and no body
        out += ["", 'const char* const %sEtag = "\\"%s\\"";' % (array_name(page.name), hashlib.sha1(packed).hexdigest()[:12])]

    out += ["", "}  // namespace webassets", "", "}  // namespace w2b", ""]

    return "\n".join(out)


def main():
    web_dir = Path(env.subst("$PROJECT_DIR")) / "web"  # noqa: F821
    gen_dir = Path(env.subst("$BUILD_DIR")) / "generated"  # noqa: F821
    header = gen_dir / "WebAssets.h"
    text = generate(web_dir)

    gen_dir.mkdir(parents=True, exist_ok=True)

    # rewritten only when the content changes, so an unchanged page rebuilds nothing
    if not header.is_file() or header.read_text(encoding="utf-8") != text:
        header.write_text(text, encoding="utf-8", newline="\n")

    env.Append(CPPPATH=[str(gen_dir)])  # noqa: F821


main()
